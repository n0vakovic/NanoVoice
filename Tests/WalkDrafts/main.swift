import Foundation
let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
defer { try? FileManager.default.removeItem(at: root) }
let store = WalkDraftStore(account: 1, peer: 2, root: root)
let initiallyEmpty = try store.hasDrafts()
assert(!initiallyEmpty)
let draft = try store.save(data: Data([1, 2, 3]), duration: 310)
let reopened = WalkDraftStore(account: 1, peer: 2, root: root)
let recovered = try reopened.drafts()
assert(recovered.count == 1 && recovered[0].id == draft.id && recovered[0].duration == 310 && recovered[0].audio == Data([1, 2, 3]))
let otherChat = try WalkDraftStore(account: 1, peer: 3, root: root).drafts()
let otherAccount = try WalkDraftStore(account: 2, peer: 2, root: root).drafts()
assert(otherChat.isEmpty && otherAccount.isEmpty)
_ = try store.save(data: Data([4]), duration: 1)
try reopened.remove(draft.id)
let remaining = try reopened.drafts()
assert(remaining.count == 1 && remaining[0].audio == Data([4]))
print("PASS: draft persistence across instances, long duration, account/chat isolation, explicit deletion")

store.retainUnsaved(data: Data([9]), duration: 4)
assert(reopened.unsaved.count == 1 && reopened.unsaved[0].0 == Data([9]))
assert(WalkDraftStore(account: 2, peer: 2, root: root).unsaved.isEmpty)
reopened.removeFirstUnsaved()
assert(store.unsaved.isEmpty)
print("PASS: emergency fallback survives controller/store instances and is account scoped")

let corruptURL = root.appendingPathComponent("WalkDrafts/1/2/corrupt.plist")
try Data([255, 0, 4]).write(to: corruptURL)
let partialListing = try reopened.listing()
assert(partialListing.drafts.count == 1 && partialListing.unreadableCount == 1)
assert(FileManager.default.fileExists(atPath: corruptURL.path))
let sendingId = partialListing.drafts[0].id
assert(store.beginSending(sendingId))
assert(!reopened.beginSending(sendingId))
assert(reopened.isSending(sendingId))
reopened.finishSending(sendingId)
assert(store.beginSending(sendingId))
store.finishSending(sendingId)
print("PASS: corrupt draft retained without blocking valid drafts; cross-instance duplicate-send guard and cleanup")
