import Foundation
let gate = WalkReplyGate()
func accept(_ id: String, peer: Int64 = 1, timestamp: Int32 = 100, now: Int32 = 100, incoming: Bool = true, audio: Bool = true) -> Bool {
    gate.accept(peer: peer, id: id, timestamp: timestamp, now: now, incoming: incoming, audio: audio)
}
assert(!accept("off"))
gate.start(peer: 1, timestamp: 100)
assert(!accept("other", peer: 2))
assert(!accept("outgoing", incoming: false))
assert(!accept("text", audio: false))
assert(!accept("history", timestamp: 99))
assert(accept("delayed", timestamp: 100, now: 10000))
assert(accept("new"))
assert(!accept("new"))
assert(accept("next", timestamp: 102, now: 102))
gate.stop()
assert(!accept("stopped"))
gate.start(peer: 2, timestamp: 200)
assert(!accept("previousChat", timestamp: 200, now: 200))
assert(accept("freshOther", peer: 2, timestamp: 200, now: 200))
print("PASS: off, peer isolation, outgoing/text/history rejection, delayed delivery, deduplication, and session reset")

var progress = WalkPlaybackProgress()
progress.reset(now: 0)
assert(!progress.stalled(now: 29, suspended: false))
assert(progress.stalled(now: 30, suspended: false))
progress.observe(position: 2, now: 30)
assert(!progress.stalled(now: 59, suspended: false))
assert(!progress.stalled(now: 600, suspended: true))
assert(!progress.stalled(now: 629, suspended: false))
assert(progress.stalled(now: 630, suspended: false))
for time in stride(from: 631.0, through: 1400, by: 1) {
    progress.observe(position: time, now: time)
    assert(!progress.stalled(now: time, suspended: false))
}
assert(WalkPlaybackProgress.resumePosition(0) == nil)
assert(WalkPlaybackProgress.resumePosition(3) == 0)
assert(WalkPlaybackProgress.resumePosition(12) == 7)
assert(WalkPlaybackProgress.retryDelay(failureCount: 1) == 5)
assert(WalkPlaybackProgress.retryDelay(failureCount: 2) == 15)
assert(WalkPlaybackProgress.retryDelay(failureCount: 3) == nil)
print("PASS: progress watchdog, recording suspension, long replies, rewind clamp, bounded retries")
